import { MAX_PAYMENT_MINOR } from '@/modules/registrations/domain/payment';
import { ApiProperty } from '@nestjs/swagger';
import { IsDefined, IsInt, IsUUID, Max, Min } from 'class-validator';

/** What the public payment page shows; no personal data. */
export class QrPaymentPageDto {
  @ApiProperty({
    format: 'uuid',
    description:
      'The registration this link pays, for the way back to its detail. The id alone grants nothing.',
  })
  registrationId!: string;

  @ApiProperty()
  eventName!: string;

  @ApiProperty({
    description:
      'Remaining debt in haléře; zero or less means there is nothing to pay.',
  })
  balanceMinor!: number;
}

export class QrPaymentInputDto {
  @ApiProperty({
    format: 'uuid',
    description:
      'Generated by the page for one attempt and sent with every retry of it: ' +
      'the same key and amount never record a second payment.',
  })
  @IsUUID('all', { message: 'Neplatný identifikátor odeslání.' })
  submissionKey!: string;

  @ApiProperty({ minimum: 1, maximum: MAX_PAYMENT_MINOR, example: 60000 })
  @IsDefined({ message: 'Zadejte částku.' })
  @IsInt({ message: 'Částka může mít nejvýše dvě desetinná místa.' })
  @Min(1, { message: 'Částka musí být větší než nula.' })
  @Max(MAX_PAYMENT_MINOR, {
    message: 'Částka může být nejvýše 10 000 000 Kč.',
  })
  amountMinor!: number;
}

export class QrPaymentResultDto {
  @ApiProperty({ description: 'Amount of the recorded payment, in haléře.' })
  paidMinor!: number;

  @ApiProperty({ description: 'Remaining debt after it, in haléře.' })
  balanceMinor!: number;
}
